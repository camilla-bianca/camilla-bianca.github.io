export function getProjectBySlug(slug) {
  return projects.find((p) => p.slug === slug)
}

export function getAdjacentProjects(slug) {
  const index = projects.findIndex((p) => p.slug === slug)
  return {
    previous: index > 0 ? projects[index - 1] : null,
    next: index < projects.length - 1 ? projects[index + 1] : null,
  }
}

// Fourth metadata field on the project detail page: labelKey and value change
// depending on where the project comes from (company, course, game jam, personal).
// The label text itself is resolved via t(`projectDetail.labels.${labelKey}`) in the component.
export function getFourthField(project) {
  if (project.origin === 'company') {
    return { labelKey: 'company', value: project.company, url: project.companyUrl }
  }
  if (project.origin === 'course') {
    return { labelKey: 'course', value: project.company, url: project.companyUrl }
  }
  if (project.origin === 'game-jam') {
    return { labelKey: 'gameJam', value: project.company, url: project.companyUrl }
  }
  return { labelKey: 'personal', value: null, url: null }
}

